def _ps(skript, **umgebung):
    """PowerShell mit UTF-8-Ausgabe; Pfade nur über die Umgebung, nie im Befehl."""
    lauf = subprocess.run(
        ["powershell", "-NoProfile", "-NonInteractive", "-Command",
         "[Console]::OutputEncoding = [Text.Encoding]::UTF8; " + skript],
        capture_output=True, text=True, encoding="utf-8", errors="replace", timeout=120,
        env=dict(os.environ, **umgebung),
        creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0))
    assert lauf.returncode == 0, lauf.stderr
    return lauf.stdout.strip()


def _windows_liest(pfad):
    """So sieht WINDOWS die Verknüpfung: Kennung über Shell.Application (die
    Eigenschaft, nach der Windows Prozess und Verknüpfung verbindet), der Rest
    über WScript.Shell. CreateShortcut auf einen vorhandenen Pfad liest nur."""
    aus = _ps(
        "$p = $env:WK_PFAD; "
        "$item = (New-Object -ComObject Shell.Application).NameSpace("
        "(Split-Path -LiteralPath $p)).ParseName((Split-Path -Leaf $p)); "
        "$l = (New-Object -ComObject WScript.Shell).CreateShortcut($p); "
        "[pscustomobject]@{kennung = $item.ExtendedProperty('System.AppUserModel.ID'); "
        "ziel = $l.TargetPath; argumente = $l.Arguments; arbeitsordner = $l.WorkingDirectory; "
        "beschreibung = $l.Description; symbol = $l.IconLocation} | ConvertTo-Json -Compress",
        WK_PFAD=str(pfad))
    return json.loads(aus)


def _fremde_verknuepfung(pfad):
    """Eine Verknüpfung, wie ein Installer oder JB sie von Hand anlegt: ohne Kennung."""
    _ps("$l = (New-Object -ComObject WScript.Shell).CreateShortcut($env:WK_PFAD); "
        "$l.TargetPath = $env:WK_ZIEL; $l.Save()",
        WK_PFAD=str(pfad), WK_ZIEL=os.path.join(os.environ["SystemRoot"], "notepad.exe"))


def _stand(pfad):
    s = os.stat(pfad)
    with open(pfad, "rb") as f:
        return (s.st_ino, s.st_mtime_ns, f.read())


def _pythonw():
    return os.path.join(os.path.dirname(sys.executable), "pythonw.exe")


# ------------------------------------------------ Was startet die Verknüpfung?

def test_quellbetrieb_startet_wie_die_bat():
    """Die Verknüpfung startet genau das, was SyncYouTube.bat startet — gemessen
    an der bat selbst (Ergebnis statt Abschrift): dasselbe pythonw, dasselbe
    Skript. Arbeitsordner ist System\\ (alle Pfade der App hängen an SCRIPT_DIR)."""
    bat = open(os.path.join(WURZEL, "SyncYouTube.bat"), encoding="utf-8").read()
    zeile = next(z for z in bat.splitlines() if z.lower().startswith("start "))
    teile = [t for t in re.findall(r'"([^"]*)"', zeile) if t]
    programm, skript = (os.path.normpath(t.replace("%~dp0", WURZEL + os.sep)) for t in teile)
    assert programm.lower().endswith("pythonw.exe") and skript.endswith("youtube_app.py"), teile
    for gestartet_mit in (programm, programm[:-len("pythonw.exe")] + "python.exe"):
        z = wk.startziel(False, gestartet_mit, MODUL_DIR)
        assert os.path.normcase(z["ziel"]) == os.path.normcase(programm), gestartet_mit
        assert z["argumente"] == f'"{skript}"'
        assert os.path.normcase(z["arbeitsordner"]) == os.path.normcase(MODUL_DIR)
        assert z["symbol"] == (z["ziel"], 0)


