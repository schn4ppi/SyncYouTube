# ------------------------------------------------ Einbau in den Server

def _main_knoten():
    baum = ast.parse(open(os.path.join(MODUL_DIR, "youtube_app.py"), encoding="utf-8").read())
    return baum, next(n for n in baum.body if isinstance(n, ast.FunctionDef) and n.name == "main")


def _name(call):
    f = call.func
    if isinstance(f, ast.Attribute) and isinstance(f.value, ast.Name):
        return f"{f.value.id}.{f.attr}"
    return getattr(f, "id", getattr(f, "attr", ""))


def _aufrufe(baum, name):
    """(Funktion der obersten Ebene, Aufruf-Knoten) für jeden AUFRUF von name."""
    return [(getattr(k, "name", "<Modulebene>"), n) for k in baum.body for n in ast.walk(k)
            if isinstance(n, ast.Call) and _name(n) == name]


def test_server_setzt_die_kennung_vor_jedem_fenster():
    """Microsoft: die Kennung „before the application presents any UI" setzen.
    Der Aufruf steht als eigene Anweisung direkt in main() (nicht in einem Zweig)
    und VOR Server (danach Ordner-Dialog), Browser, SMTC-Fenster und Tray.
    Ein Import von youtube_app setzt nichts."""
    baum, main = _main_knoten()
    wo = _aufrufe(baum, "windows_kennung.setze_kennung")
    assert [f for f, _ in wo] == ["main"], wo
    stelle = next((a for a in main.body if isinstance(a, ast.Expr) and a.value is wo[0][1]), None)
    assert stelle is not None, "setze_kennung() steht nicht als eigene Anweisung direkt in main()"
    spaeter = {"_smtc_einrichten", "_tray_icon", "ThreadingHTTPServer", "webbrowser.open",
               "threading.Timer", "windows_kennung.startmenue_eintrag"}
    ui = sorted((n.lineno, _name(n)) for n in ast.walk(main)
                if isinstance(n, ast.Call) and _name(n) in spaeter)
    assert {name for _, name in ui} == spaeter, f"Wächter blind: gefunden {ui}"
    assert stelle.lineno < ui[0][0], f"setze_kennung erst in Zeile {stelle.lineno}, vorher {ui[0]}"


def test_startmenue_eintrag_nur_beim_echten_start():
    """Einmal je Start, in main(), im Hintergrund (faden=True), hinter dem
    Einzel-Instanz-Riegel (nach dem Server-Bind) und NIE im Testmodus."""
    baum, main = _main_knoten()
    wo = _aufrufe(baum, "windows_kennung.startmenue_eintrag")
    assert [f for f, _ in wo] == ["main"], wo
    aufruf = wo[0][1]
    eltern = {kind: knoten for knoten in ast.walk(main) for kind in ast.iter_child_nodes(knoten)}
    knoten, zweige = aufruf, []
    while knoten in eltern:
        knoten = eltern[knoten]
        if isinstance(knoten, ast.If):
            zweige.append(ast.unparse(knoten.test))
    assert "not TESTMODUS" in zweige, f"nicht durch 'if not TESTMODUS' geschützt: {zweige}"
    assert any(k.arg == "faden" and getattr(k.value, "value", None) is True
               for k in aufruf.keywords), "blockiert den Start (faden=True fehlt)"
    bind = min(n.lineno for n in ast.walk(main)
               if isinstance(n, ast.Call) and _name(n) == "ThreadingHTTPServer")
    assert aufruf.lineno > bind, "vor dem Einzel-Instanz-Riegel: eine Zweit-Instanz schriebe mit"


def test_exe_nimmt_windows_kennung_mit(monkeypatch):
    """Die Bauvorschrift wird mit Attrappen ausgeführt: windows_kennung steht in
    den hiddenimports (JB: „auch in der exe bei Freunden")."""
    def collect_all(name):
        return ([], [], [])
    hooks = types.ModuleType("PyInstaller.utils.hooks")
    hooks.collect_all = collect_all
    for name, mod in (("PyInstaller", types.ModuleType("PyInstaller")),
                      ("PyInstaller.utils", types.ModuleType("PyInstaller.utils")),
                      ("PyInstaller.utils.hooks", hooks)):
        monkeypatch.setitem(sys.modules, name, mod)
    analyse = {}

    def Analysis(skripte, **kw):
        analyse.update(kw)
        return types.SimpleNamespace(pure=[], scripts=[], binaries=[], datas=[])
    g = {"__name__": "__spec__", "Analysis": Analysis,
         "PYZ": lambda *a, **k: None, "EXE": lambda *a, **k: None}
    spec = open(os.path.join(MODUL_DIR, "SyncYouTube.spec"), encoding="utf-8").read()
    exec(compile(spec, "SyncYouTube.spec", "exec"), g)
    assert "windows_kennung" in analyse["hiddenimports"]
