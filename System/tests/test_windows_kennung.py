# ------------------------------------------------ Kennung des Prozesses

def test_kennung_wirkt_im_eigenen_prozess():
    """Eigener Kindprozess (der Testprozess bleibt unberührt): vorher hat er
    keine ausdrückliche Kennung, nach setze_kennung() liest Windows JBK.SyncYouTube."""
    code = ("import ctypes, sys; sys.path.insert(0, sys.argv[1]); import windows_kennung as w\n"
            "def lies():\n"
            "    p = ctypes.c_wchar_p()\n"
            "    hr = ctypes.windll.shell32.GetCurrentProcessExplicitAppUserModelID(ctypes.byref(p))\n"
            "    return p.value if hr == 0 else None\n"
            "vorher = lies(); ok = w.setze_kennung(); print(vorher, ok, lies())\n")
    lauf = subprocess.run([sys.executable, "-B", "-c", code, MODUL_DIR], capture_output=True,
                          text=True, timeout=60)
    assert lauf.stdout.split() == ["None", "True", KENNUNG], (lauf.stdout, lauf.stderr)


class _Shell32:
    def __init__(self, antwort=0, fehler=None):
        self.antwort, self.fehler, self.gesetzt = antwort, fehler, []

    def SetCurrentProcessExplicitAppUserModelID(self, kennung):
        if self.fehler:
            raise self.fehler
        self.gesetzt.append(getattr(kennung, "value", kennung))
        return self.antwort


def test_kennung_scheitert_still():
    """Ein Fehlschlag (Ausnahme oder Fehler-HRESULT) reißt den Start nie: False + Protokoll."""
    log = []
    gut = _Shell32()
    assert wk.setze_kennung(log=log.append, shell32=gut) is True
    assert gut.gesetzt == [KENNUNG] and log == []
    assert wk.setze_kennung(log=log.append, shell32=_Shell32(fehler=OSError("verweigert"))) is False
    assert wk.setze_kennung(log=log.append, shell32=_Shell32(antwort=-2147024809)) is False
    assert len(log) == 2 and all("Kennung" in z for z in log), log


