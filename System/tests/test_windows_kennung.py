"""Windows-Kennung + Startmenü-Eintrag (windows_kennung.py, JB 24.09.2026:
„Kennung + Startmenü-Eintrag").

Befund (Analyse auslieferung, Befund 3): Ohne eigene App-Kennung ordnet
Windows den pythonw-Prozess des Servers per Heuristik der einzigen
Startmenü-Verknüpfung auf pythonw.exe zu, „IDLE (Python 3.14)"
(Microsoft.AutoGenerated.{9C659DC1…}, gemessen 23.09.).

Geprüft wird das ERGEBNIS:
* die Kennung, die Windows dem Prozess danach wirklich zuschreibt (eigener
  Kindprozess, Rücklesen per GetCurrentProcessExplicitAppUserModelID);
* die Verknüpfung, wie WINDOWS sie liest (PowerShell: Shell.Application und
  WScript.Shell), nicht wie unser eigener Leser sie liest;
* die Reihenfolge in huelle.main() per Attrappe; für youtube_app.main() (zu
  groß für einen Lauf im Test) der Aufruf im Syntaxbaum — Aufruf statt
  Erwähnung, wie der Wächter „_smtc_einrichten nur in main".

JBs echtes Startmenü berührt KEIN Test: jeder Schreib-Test bekommt tmp_path,
und die Wache aus tests/conftest.py sperrt den Standard-Ordner in JEDEM Test
(laut, auch im Hintergrundfaden — geprüft in tests/test_wachen.py).
"""
